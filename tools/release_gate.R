     proven(suite_problems, bad = "[ FAIL 1 | WARN 0 | SKIP 0 | PASS 10 ]", good = "[ FAIL 0 | WARN 0 | SKIP 2 | PASS 10 ]") &&
       length(suite_problems(rout_lines)) == 0L,
