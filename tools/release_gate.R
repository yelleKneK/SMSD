# One help page's examples. Pages over 1 s are listed, so a creep toward the
# ceiling is seen before it arrives.
over_budget <- function(et) {
  et$most <- pmax(et$user + et$system, et$elapsed)
  sprintf("%s %.2f s", et$name[et$most > page_budget_s], et$most[et$most > page_budget_s])
}
ex_file <- file.path(rcheck, paste0(pkg, "-Ex.timings"))
# A timings table with a header and no rows, or with fewer rows than there
# are help pages with examples, is a check that did not time the examples,
# and nothing can be concluded from the rows that are missing.
has_examples <- vapply(tools::Rd_db(dir = root), function(rd)
  any(vapply(rd, function(x) identical(attr(x, "Rd_tag"), "\\examples"), logical(1))), logical(1))
untimed <- function(x) {
  if (x$timed == 0L) "the timings file has no rows: no page's examples were timed"
  else if (x$timed < x$expected)
    sprintf("the timings file lists %d page(s); %d help pages have examples", x$timed, x$expected)
  else character()
}
