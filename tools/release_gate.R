# The log is read step by step: each "* checking ..." line with the lines
# under it is one block.
# The status is the last word of the heading, or stands alone on a later
# line when the step printed something first (the tests do).
check_blocks <- function(log) {
  heads <- grep("^\\* ", log)
  ends <- c(heads[-1L] - 1L, length(log))
  word <- "(OK|NOTE|WARNING|ERROR)"
  lapply(seq_along(heads), function(k) {
    head <- sub("\\s+$", "", log[heads[k]])
    body <- sub("\\s+$", "", log[seq_len(ends[k] - heads[k]) + heads[k]])
    alone <- grep(paste0("^ *(\\[[0-9]+s/[0-9]+s\\] )?", word, "$"), body, value = TRUE)
    list(head = head,
         status = if (grepl(paste0("\\.\\.\\..* ", word, "$"), head)) sub(paste0("^.* ", word, "$"), "\\1", head)
                  else if (length(alone)) sub(paste0("^.*", word, "$"), "\\1", alone[length(alone)]) else "",
         body = body[nzchar(trimws(body))])
  })
}
# The entries under "Found the following (possibly) invalid URLs:", each a
# URL line and the indented lines that belong to it.
url_entries <- function(body) {
  at <- grep("^ *URL: ", body)
  lapply(at, function(i) {
    j <- i
    while (j < length(body) && grepl("^ +(From|Status|Message|CRAN URL not in canonical form):? ", body[j + 1L])) j <- j + 1L
    list(rows = i:j, url = sub(" \\(moved to .*\\)$", "", sub("^ *URL: ", "", body[i])),
         status = sub("^ *Status: ", "", grep("^ *Status: ", body[i:j], value = TRUE))[1L])
  })
}
# A URL that failed with a 5xx response or a timeout when the check asked is
# asked again: that is the network's moment, not the package's. Only a
# problem that repeats stays in the note; every flagged URL is printed. The
# package's own page on CRAN answers 404 until the package is accepted, so
# for a first release (and only then) that one answer is not a finding.
own_cran_page <- function(url) {
  grepl(sprintf("^https?://cran[.]r-project[.]org/(package=%s|web/packages/%s(/|/index[.]html)?)$", pkg, pkg),
        url, ignore.case = TRUE)
}
ask_again <- function(url) {
  tryCatch(system2("curl", c("-s", "-o", "/dev/null", "-w", "%{http_code}", "-L", "--max-time", "20", shQuote(url)),
                   stdout = TRUE, stderr = FALSE), error = function(e) "000")
}
drop_transient_urls <- function(body, ask = ask_again, not_on_cran = FALSE) {
  drop <- integer()
  entries <- url_entries(body)
  for (e in entries) {
    if (!is.na(e$status) && grepl("^5|^Error", e$status) && identical(ask(e$url), "200")) {
      cat("       transient at check time (", e$status, "); asked again and got 200: ", e$url, "\n", sep = "")
      drop <- c(drop, e$rows)
    } else if (not_on_cran && !is.na(e$status) && grepl("^404", e$status) && own_cran_page(e$url)) {
      cat("       the package's own page on CRAN, which exists only after acceptance (404 now): ", e$url, "\n", sep = "")
      drop <- c(drop, e$rows)
    }
  }
  if (length(entries) && length(unique(drop)) == length(unlist(lapply(entries, `[[`, "rows"))))
    drop <- c(drop, grep("invalid URLs:$", body))
  if (length(drop)) body[-drop] else body
}
wordlist <- readLines("inst/WORDLIST", warn = FALSE, encoding = "UTF-8")
# Why a NOTE may not pass: character(0) when it is one of the declared notes.
note_objection <- function(block, ask = ask_again, not_on_cran = FALSE) {
  body <- block$body
  if (grepl("CRAN incoming feasibility", block$head)) {
    rest <- drop_transient_urls(body, ask, not_on_cran)
    rest <- rest[!grepl("^Maintainer: |^New submission$", trimws(rest))]
    if (any(grepl("^Possibly misspelled words in DESCRIPTION:", rest))) {
      listed <- grepl("^ +\\S+ \\([0-9]+:[0-9]+", rest)
      if (all(sub(" \\(.*$", "", trimws(rest[listed])) %in% wordlist))
        rest <- rest[!listed & !grepl("^Possibly misspelled words in DESCRIPTION:", rest)]
    }
    return(rest)
  }
  if (grepl("HTML version of manual", block$head)) {
    skipping <- grepl("^Skipping checking (HTML validation|math rendering)", trimws(body))
    advice <- any(skipping) & grepl("^Please obtain a recent version of HTML Tidy|^release or compiling the source code from",
                                    trimws(body))
    return(body[!skipping & !advice])
  }
  # R 4.6 prints two lines when no time server answered; R 4.5 and earlier
  # printed one. Those lines pass and nothing else under this heading does: a
  # file dated in the future is listed under the same heading and stays.
  if (grepl("future file timestamps", block$head))
    return(body[!grepl(paste0("^unable to verify current time$|",
                              "^Unable to verify current time[.] +To disable remote verification,$|",
                              "^set environment variable _R_CHECK_SYSTEM_CLOCK_ to a false value[.]$"),
                       trimws(body))])
  body
}
# The counts in the check's own Status line ("Status: 1 WARNING, 2 NOTEs").
status_counts <- function(status_line) {
  count <- function(kind) {
    m <- regmatches(status_line, regexpr(paste0("[0-9]+ ", kind), status_line))
    if (length(m)) as.integer(sub(" .*$", "", m)) else 0L
  }
  c(ERROR = count("ERROR"), WARNING = count("WARNING"), NOTE = count("NOTE"))
}
verdict <- function(log, ask = ask_again, not_on_cran = FALSE) {
  blocks <- check_blocks(log)
  st <- vapply(blocks, `[[`, "", "status")
  serious <- unlist(lapply(blocks[st %in% c("ERROR", "WARNING")], function(b) c(b$head, paste0("  ", b$body))))
  notes <- unlist(lapply(blocks[st == "NOTE"], function(b) {
    why <- note_objection(b, ask, not_on_cran)
    if (length(why)) c(b$head, paste0("  ", why))
  }))
  status_line <- grep("^Status:", log, value = TRUE)
  finished <- length(status_line) > 0L
  if (!finished) {
    serious <- c(serious, "the log has no Status line: the check did not finish")
  } else {
    # Every ERROR, WARNING, and NOTE the check counted must have been read
    # here; one that was not read was not examined, and that is not a pass.
    said <- status_counts(status_line[length(status_line)])
    read <- c(ERROR = sum(st == "ERROR"), WARNING = sum(st == "WARNING"), NOTE = sum(st == "NOTE"))
    off <- names(said)[said != read]
    serious <- c(serious, sprintf("the Status line counts %d %s(s) and %d could be read from the log, so a result went unexamined",
                                  said[off], off, read[off]))
  }
  list(serious = serious, notes = notes, finished = finished)
}
