# `detail` is printed and recorded when a gate does not pass; `info` always.
gate <- function(name, status, detail = character(), info = character()) {
  if (is.logical(status)) status <- if (isTRUE(status)) "PASS" else "FAIL"
  shown <- c(if (status != "PASS") detail, info)
  cat(sprintf("[%s] %s\n", status, name))
  for (d in shown) cat("       ", d, "\n", sep = "")
  state$results[[length(state$results) + 1L]] <- list(name = name, status = status, detail = shown)
  invisible(status == "PASS")
}
statuses <- function() vapply(state$results, `[[`, character(1), "status")
run <- function(cmd, args, log, env = character()) {
  status <- suppressWarnings(system2(cmd, args, stdout = log, stderr = log, env = env))
  list(status = status, lines = if (file.exists(log)) readLines(log, warn = FALSE) else character())
}
# A known bad input must be flagged and a known clean one passed before a
# detector's verdict on the package is believed. A detector that stops or
# warns on either has not been proven.
proven <- function(detector, bad, good) {
  no <- function(e) FALSE
  isTRUE(tryCatch(length(detector(bad)) > 0L, error = no, warning = no)) &&
    isTRUE(tryCatch(length(detector(good)) == 0L, error = no, warning = no))
}
