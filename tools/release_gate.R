# ---- 1. Static Checks (tools/release_checks.R) --------------------------------
# One gate for each line the script prints, so the record carries every
# result. The script proves each of its detectors on a control of its own.
read_checks <- function(res, prefix) {
  heads <- grep("^\\[(PASS|FAIL)\\] ", res$lines)
  if (!length(heads) || !any(grepl("^[0-9]+ check\\(s\\), [0-9]+ failed[.]$", res$lines))) {
    gate(sprintf("%s: the checks ran to completion", prefix), FALSE,
         c(sprintf("exit status %s; the last lines were:", res$status), utils::tail(res$lines, 8L)))
    return(invisible())
  }
  ends <- c(heads[-1L] - 1L, length(res$lines))
  for (k in seq_along(heads)) {
    line <- res$lines[heads[k]]
    detail <- trimws(res$lines[seq_len(ends[k] - heads[k]) + heads[k]])
    detail <- detail[nzchar(detail) & !grepl("^[0-9]+ check\\(s\\), [0-9]+ failed[.]$", detail)]
    passed <- startsWith(line, "[PASS]")
    gate(sprintf("%s: %s", prefix, sub("^\\[(PASS|FAIL)\\] ", "", line)), passed,
         detail = if (!passed) detail else character(), info = if (passed) detail else character())
  }
  failed <- sum(grepl("^\\[FAIL\\] ", res$lines))
  if ((res$status != 0L) != (failed > 0L))
    gate(sprintf("%s: the exit status agrees with the lines printed", prefix), FALSE,
         sprintf("exit status %s with %d failing line(s)", res$status, failed))
}
