# The check's own clock. One [cpu/elapsed] pair for each timed step.
timings <- grep("\\[[0-9]+s/[0-9]+s\\]", log, value = TRUE)
step_secs <- function(pattern, lines = timings) {
  l <- grep(pattern, lines, value = TRUE)[1L]
  if (is.na(l)) return(c(cpu = NA_real_, elapsed = NA_real_))
  v <- as.numeric(strsplit(gsub("[][s]", "", regmatches(l, regexpr("\\[[0-9]+s/[0-9]+s\\]", l))), "/")[[1L]])
  c(cpu = v[1L], elapsed = v[2L])
}
