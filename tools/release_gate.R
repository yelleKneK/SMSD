           !proven(untimed, bad = list(timed = 2L, expected = 3L), good = list(timed = 4L, expected = 3L))) {
  gate("the check timed the examples of every help page that has them", FALSE, broken)
} else if (length(untimed(list(timed = nrow(utils::read.table(ex_file, header = TRUE)), expected = sum(has_examples))))) {
