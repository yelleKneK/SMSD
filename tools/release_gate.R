# The one-minute load average, from `uptime`, against the cores that can give
# the check full speed (the performance cores, where the machine has two
# kinds). A quiet machine leaves at least one of them free.
fast_cores <- function() {
  n <- suppressWarnings(tryCatch(as.integer(system2("sysctl", c("-n", "hw.perflevel0.physicalcpu"),
                                                     stdout = TRUE, stderr = FALSE)), error = function(e) NA_integer_))
  if (length(n) != 1L || is.na(n)) n <- parallel::detectCores(logical = FALSE)
  if (length(n) != 1L || is.na(n)) 1L else n
}
load_now <- function(uptime_line) {
  m <- regmatches(uptime_line, regexpr("load averages?: *[0-9.]+", uptime_line, useBytes = TRUE))
  if (length(m)) as.numeric(sub("^.*: *", "", m)) else NA_real_
}
too_busy <- function(x) {
  if (is.na(x$load)) return("the load average could not be read")
  if (x$load > x$limit) sprintf("load %.2f, over the limit of %.2f", x$load, x$limit) else character()
}
gate_load <- function(when, own = 0) {
  line <- tryCatch(suppressWarnings(system2("uptime", stdout = TRUE, stderr = FALSE)), error = function(e) character())
  now <- list(load = if (length(line)) load_now(line[1L]) else NA_real_, limit = fast_cores() - 1 + own)
  ok <- proven(too_busy, bad = list(load = load_now("22:05  up 4 days, 1 user, load averages: 100.50 95.72 76.83"), limit = 3),
               good = list(load = load_now(" 10:01:02 up 1 day,  2 users,  load average: 0.52, 0.58, 0.59"), limit = 3))
  gate(sprintf("the machine is idle %s (one-minute load average %.2f; %d fast cores, limit %.2f)",
               when, now$load, fast_cores(), now$limit),
       ok && length(too_busy(now)) == 0L,
       if (!ok) broken else c(too_busy(now), "other work is running here, so the times this run records cannot be certified;",
                              "close it and run the gate again"))
}

# ---- Full Mode Only: What Must Hold Before Anything Runs ---------------------
if (!quick) {
  # 1. The machine stays awake. `caffeinate -i` holds an assertion that
  # prevents idle sleep; the gate looks for it and refuses to start without.
  # The list of assertions names other processes and the devices they hold,
  # and a device name need not be valid text in this session's encoding (an
  # apostrophe from an older encoding is enough). The search is by bytes, so
  # such a line raises no warning and hides nothing; the controls carry one.
  awake <- function(lines) {
    if (any(grepl("pid [0-9]+\\(caffeinate\\).*PreventUserIdleSystemSleep", lines, useBytes = TRUE))) character() else
      "no caffeinate assertion that prevents idle sleep"
  }
  if (Sys.info()[["sysname"]] == "Darwin") {
    assertions <- tryCatch(suppressWarnings(system2("pmset", c("-g", "assertions"), stdout = TRUE, stderr = FALSE)),
                           error = function(e) character())
    odd_bytes <- rawToChar(as.raw(c(utf8ToInt("   pid 9(Window): [0x2] 00:00:02 UserIsActive named: \"K"), 213L,
                                    utf8ToInt("s Mouse\""))))
    ok <- proven(awake,
                 bad = c("   PreventUserIdleSystemSleep     1", odd_bytes,
                         "   pid 10(caffeinate): [0x1] 00:00:01 PreventUserIdleDisplaySleep named: \"x\""),
                 good = c(odd_bytes,
                          "   pid 10(caffeinate): [0x1] 00:00:01 PreventUserIdleSystemSleep named: \"caffeinate command-line tool\""))
    gate("the machine is kept awake for the timing gates (a caffeinate assertion is held)",
         ok && length(awake(assertions)) == 0L,
         if (!ok) broken else "start with: caffeinate -i Rscript tools/release_gate.R --record=DIR")
  } else {
    gate("the machine is kept awake for the timing gates", "SKIP",
         "not macOS: make sure this machine cannot sleep or suspend during the run")
  }

