run_suite <- function(dir, lib_first, tag) {
  env <- c("NOT_CRAN=true", if (nzchar(lib_first))
    paste0("R_LIBS=", shQuote(paste(c(lib_first, .libPaths()), collapse = .Platform$path.sep))))
  res <- run("Rscript", c(shQuote(runner), pkg, shQuote(dir), shQuote(lib_first),
                          shQuote(file.path(work, paste0(tag, "-timings.csv")))),
             file.path(work, paste0(tag, ".log")), env = env)
  line <- grep("^SUITE passed=", res$lines, value = TRUE)
  n <- if (length(line) == 1L) as.integer(regmatches(line, gregexpr("[0-9]+", line))[[1L]]) else rep(NA_integer_, 5L)
  list(n = stats::setNames(n, c("passed", "failed", "errors", "warnings", "skipped")),
       detail = sub("^SUITE-DETAIL ", "", grep("^SUITE-DETAIL ", res$lines, value = TRUE)),
       tail = utils::tail(res$lines, 6L), status = res$status)
}
suite_verdict <- function(s) {
  if (anyNA(s$n)) return(c("the suite did not report a result", s$tail))
  skipped <- grep("[|] skipped$", s$detail, value = TRUE)
  unexplained <- skipped[!vapply(skipped, function(d)
    any(vapply(allowed_skips, grepl, logical(1), x = d, fixed = TRUE)), logical(1))]
  c(if (s$n[["failed"]] > 0L || s$n[["errors"]] > 0L || s$n[["warnings"]] > 0L)
      c(sprintf("%d failed, %d errors, %d warnings:", s$n[["failed"]], s$n[["errors"]], s$n[["warnings"]]),
        grep("[|] skipped$", s$detail, value = TRUE, invert = TRUE)),
    if (s$n[["passed"]] == 0L) "no expectation ran",
    if (length(unexplained) || s$n[["skipped"]] > length(skipped))
      c("skipped, and not in the gate's list of allowed skips:", unexplained))
}
