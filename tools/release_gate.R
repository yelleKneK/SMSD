# pkgdown refuses a page that no section claims. It does not refuse the
# reverse: a selector that matches nothing passes in silence, so a section
# emptied by a removal or a rename stays in the index with nothing under it.
# Each section is resolved here the way pkgdown resolves it (a selector sees
# a page's name and its aliases, and a page marked internal is left out). An
# entry written in a form this reading does not know is reported, not
# skipped. A page that this reading leaves unclaimed is reported too when
# pkgdown accepted the index, since then the two readings differ; when
# pkgdown refused the index, its own message names the unclaimed pages.
resolve_entry <- function(entry, topics) {
  public <- !vapply(topics, `[[`, logical(1), "internal")
  labels <- lapply(topics, function(t) c(t$name, t$aliases))
  any_label <- function(f) which(public & vapply(labels, function(l) any(f(l)), logical(1)))
  exact <- which(vapply(labels, function(l) entry %in% l, logical(1)))
  if (length(exact)) return(list(rows = exact, negative = FALSE))
  m <- regmatches(entry, regexec("^(-?) *(starts_with|ends_with|matches|contains)\\(\"(.*)\"\\)$", entry))[[1L]]
  if (!length(m)) return(NULL)
  x <- m[4L]
  rows <- switch(m[3L],
                 starts_with = any_label(function(l) grepl(paste0("^", x), l)),
                 ends_with = any_label(function(l) grepl(paste0(x, "$"), l)),
                 matches = any_label(function(l) grepl(x, l)),
                 contains = any_label(function(l) grepl(x, l, fixed = TRUE)))
  list(rows = rows, negative = nzchar(m[2L]))
}
index_problems <- function(x, pkgdown_accepted = TRUE) {
  out <- character(); claimed <- integer()
  for (section in x$index) {
    if (is.null(section$contents)) next
    label <- c(section$title, section$subtitle, "(untitled)")[1L]
    rows <- integer()
    for (k in seq_along(section$contents)) {
      r <- resolve_entry(section$contents[[k]], x$topics)
      if (is.null(r)) { out <- c(out, sprintf("section \"%s\": the entry %s is in a form this check cannot read", label, section$contents[[k]])); next }
      if (r$negative && k == 1L) rows <- which(!vapply(x$topics, `[[`, logical(1), "internal"))
      rows <- if (r$negative) setdiff(rows, r$rows) else union(rows, r$rows)
    }
    if (!length(rows)) out <- c(out, sprintf("section \"%s\" matches no %s", label, x$what))
    claimed <- union(claimed, rows)
  }
  lost <- setdiff(which(!vapply(x$topics, `[[`, logical(1), "internal")), claimed)
  c(out, if (pkgdown_accepted && length(lost))
    sprintf("%s is claimed by no section as this check reads the index, though pkgdown accepted it",
            vapply(x$topics[lost], `[[`, "", "name")))
}
