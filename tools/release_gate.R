# The tests as CRAN ran them, read from the check's own output.
suite_counts <- function(lines) {
  l <- grep("^\\[ FAIL [0-9]+ \\| WARN [0-9]+ \\| SKIP [0-9]+ \\| PASS [0-9]+ \\]", lines, value = TRUE)
  if (!length(l)) return(NULL)
  n <- as.integer(regmatches(l[length(l)], gregexpr("[0-9]+", l[length(l)]))[[1L]])
  stats::setNames(n, c("fail", "warn", "skip", "pass"))
}
suite_problems <- function(lines) {
  n <- suite_counts(lines)
  if (is.null(n)) return("no testthat summary line was found")
  c(if (n[["fail"]] > 0L) sprintf("%d failed", n[["fail"]]),
    if (n[["warn"]] > 0L) sprintf("%d warning(s)", n[["warn"]]),
    if (n[["pass"]] == 0L) "no expectation ran")
}
