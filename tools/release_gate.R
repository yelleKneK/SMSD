if (!proven(drift,
            bad = list(before = c(a = "1", b = "2"), after = c(a = "1", b = "3", c = "4")),
            good = list(before = c(a = "1", b = "2"), after = c(a = "1", b = "2")))) {
  gate("documentation current (roxygen regenerates nothing)", FALSE, broken)
} else {
  stale <- drift(list(before = before, after = after))
  gate("documentation current (roxygen regenerates nothing and reports no problem)",
       rox$status == 0L && length(stale) == 0L && length(rox_problems) == 0L,
       c(if (rox$status != 0L) c(sprintf("roxygen2::roxygenise() exited with status %s", rox$status), utils::tail(rox$lines, 6L)),
         if (length(stale)) c("regenerated just now, so commit them:", stale),
         rox_problems))
}

# ---- 3. The PDF Manual Renders Through LaTeX ------------------------------------
# The step that catches Rd markup inside math. The control is a one-page
# manual with \code{} inside \eqn{}, which must fail to render.
latex_errors <- function(res) {
  c(if (res$status != 0L) sprintf("R CMD Rd2pdf exit status %s", res$status),
    if (!file.exists(res$pdf)) "no PDF was written",
    utils::head(grep("^! |LaTeX errors|Missing \\$ inserted", res$lines, value = TRUE), 10L))
}
rd2pdf <- function(what, tag) {
  out <- file.path(work, paste0(tag, ".pdf")); unlink(out)
  # Run from the temporary directory: Rd2pdf keeps its build folder in the
  # working directory, and a failed run can leave it behind.
  res <- local({
    old <- setwd(work); on.exit(setwd(old))
    run("R", c("CMD", "Rd2pdf", "--no-preview", "--force", paste0("--output=", shQuote(out)), shQuote(what)),
        file.path(work, paste0(tag, ".log")))
  })
  res$pdf <- out
  res
}
