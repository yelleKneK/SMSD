# The release gate for SMSD: the check CRAN runs, run here first, in full.
#
# No tarball leaves this machine without a full-mode run of this script
# printing ALL GATES PASSED and writing its record, with the commit and the
# tarball's sha256, to a folder outside the repository. The file to upload is
# the one the gate copied to that folder; if its sha256 does not match the
# record, it is not certified.
#
# Usage, from the package root:
#   Rscript tools/release_gate.R --quick
#       The static half, about a minute. Run it after any edit to the
#       documentation, before the commit. Works on an uncommitted tree.
#   caffeinate -i Rscript tools/release_gate.R --record=DIR
#       Full mode, before any tarball leaves. DIR is where the record and the
#       certified tarball are written; it must exist and lie outside the
#       repository. The environment variable SMSD_GATE_RECORD may name it
#       in place of the argument.
#   Rscript tools/release_checks.R --history
#       The sweep of the history and of the identities behind it, alone (a
#       few seconds). Run it before any push, the first one included: full
#       mode repeats it as its last step, but full mode cannot pass until
#       the site address is in DESCRIPTION, and the site exists only after
#       a push. Quick mode does not run it, because quick mode is run on
#       working branches whose history is not the one that will be pushed.
#
# What full mode enforces:
#   * It certifies a commit, not a draft: the working tree must be clean, and
#     the tarball is built from `git archive HEAD` in a temporary directory
#     that no file synchronization service touches.
#   * Nothing is disabled: R CMD check --as-cran with both manuals built and
#     the remote checks on.
#   * No ERROR and no WARNING passes, and there is no list of exceptions for
#     either. The only NOTEs that pass are the ones declared in
#     `declared_notes` below. Every result the check's Status line counts
#     must have been read from the log; one that was not read fails the gate.
#   * A step the machine cannot run is reported as SKIP, never as PASS, and
#     that includes a step R CMD check skips without saying so.
#   * The timings are read from the check's own files, so on macOS the run
#     must be wrapped in `caffeinate -i` (a machine that sleeps in the middle
#     records minutes of elapsed time against seconds of work), and the
#     machine must be idle: the load average is read before and after the
#     check, and a busy machine fails the gate.
#   * The tests are run against the tarball installed in a scratch library,
#     not against whatever happens to be installed.
#   * Every detector is first shown a known bad input and must flag it.
#
# Do not edit this file while a run is in progress: R reads a script as it
# goes. Never edit it to make a failing run pass; if a release must go out
# over a failure, the gate fails, the record says so, and the decision is
# written beside it.
#
# tools/ is excluded from the tarball by .Rbuildignore.

