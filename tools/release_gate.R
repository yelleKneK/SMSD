# ---- 2. Documentation Current -------------------------------------------------
# man/ and NAMESPACE are generated. Regenerating them must change nothing;
# compared by content, so a touched file does not count.
doc_state <- function() {
  f <- c(list.files("man", pattern = "[.]Rd$", full.names = TRUE), "NAMESPACE", "DESCRIPTION")
  tools::md5sum(f)
}
drift <- function(x) {
  b <- x$before; a <- x$after
  c(setdiff(names(a), names(b)), setdiff(names(b), names(a)),
    names(b)[names(b) %in% names(a) & b != a[names(b)]])
}
